for n in range(100, 1000):
    # Превращаем число в строку, чтобы легко достать цифры
    s = str(n)
    d1 = int(s[0])
    d2 = int(s[1])
    d3 = int(s[2])

    # Вычисляем произведения по правилу 1
    p1 = d1 * d2
    p2 = d2 * d3

    # Сортируем произведения в порядке НЕВОЗРАСТАНИЯ (от большего к меньшему)
    res_list = sorted([p1, p2], reverse=True)

    # Склеиваем числа в одну строку (важно превратить их в str)
    res_str = str(res_list[0]) + str(res_list[1])

    # Проверяем условие задачи
    if res_str == "205":
        print(f"Минимальное число: {n}")
        break  # Нашли первое (наименьшее) и выходим